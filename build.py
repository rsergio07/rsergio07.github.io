def build_page(d: dict) -> str:
    site = d["site"]
    sections = [
        build_hero(d),
        build_about(d),
        build_timeline(d),
        build_certifications(d),
        build_projects(d),
        build_writing(d),
    ]
    labs = build_labs(d)
    if labs:
        sections.append(labs)

    nav_items = [
        ("approach", "Approach"),
        ("track-record", "Track record"),
        ("projects", "Projects"),
        ("writing", "Writing"),
    ]
    if labs:
        nav_items.append(("labs", d["labs"]["heading"]))
    nav = "\n".join(
        f'      <li><a href="#{a(i)}">{e(label)}</a></li>' for i, label in nav_items
    )

    og_image = site["url"] + "assets/og-image.png"

    return f"""<!DOCTYPE html>
<html lang="en">
<head>
{BANNER}
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<meta http-equiv="Content-Security-Policy" content="default-src 'self'; script-src 'self' 'unsafe-inline'; style-src 'self' 'unsafe-inline' https://fonts.googleapis.com; font-src 'self' https://fonts.gstatic.com; img-src 'self' data:; connect-src 'none'; base-uri 'none'; form-action 'none'; object-src 'none'">

<title>{e(site["title"])}</title>
<meta name="description" content="{a(site["description"])}">
<link rel="canonical" href="{a(site["url"])}">

<meta property="og:type" content="profile">
<meta property="og:site_name" content="{a(site["shortName"])}">
<meta property="og:title" content="{a(site["title"])}">
<meta property="og:description" content="{a(site["description"])}">
<meta property="og:url" content="{a(site["url"])}">
<meta property="og:image" content="{a(og_image)}">
<meta property="og:image:width" content="1200">
<meta property="og:image:height" content="630">
<meta property="og:image:alt" content="{a(site["name"])} — {a(site["role"])}">
<meta name="twitter:card" content="summary_large_image">
<meta name="twitter:title" content="{a(site["title"])}">
<meta name="twitter:description" content="{a(site["description"])}">
<meta name="twitter:image" content="{a(og_image)}">

<meta name="theme-color" content="#f3f2ee" media="(prefers-color-scheme: light)">
<meta name="theme-color" content="#14181b" media="(prefers-color-scheme: dark)">
<link rel="icon" href="assets/favicon.svg" type="image/svg+xml">

<link rel="preconnect" href="https://fonts.googleapis.com">
<link rel="preconnect" href="https://fonts.gstatic.com" crossorigin>
<link rel="stylesheet" href="https://fonts.googleapis.com/css2?family=Archivo:wdth,wght@100,400;100,600;112,700;125,800&family=Source+Serif+4:opsz,wght@8..60,400;8..60,600&display=swap">
<link rel="stylesheet" href="style.css">

<script type="application/ld+json">
{build_jsonld(d)}
</script>

<script>
/* Applied before paint so the page never flashes the wrong theme. */
(function () {{
  try {{
    var saved = localStorage.getItem('theme');
    if (saved === 'light' || saved === 'dark') {{
      document.documentElement.dataset.theme = saved;
    }}
  }} catch (err) {{ /* storage blocked; system preference applies */ }}
}})();
</script>
</head>
<body>
<a class="skip" href="#main">Skip to content</a>

<header class="topbar">
  <a class="topbar__mark" href="#main"><span>SR</span></a>
  <nav class="topbar__nav" aria-label="Sections">
    <ul>
{nav}
    </ul>
  </nav>
  <button class="theme" type="button" id="theme-toggle" aria-pressed="false">
    <span class="theme__label">Dark</span>
  </button>
</header>

<main id="main">
{"".join(sections)}
</main>
{build_footer(d)}

<script>
(function () {{
  var root = document.documentElement;
  var btn = document.getElementById('theme-toggle');
  if (!btn) return;
  var label = btn.querySelector('.theme__label');

  function current() {{
    if (root.dataset.theme) return root.dataset.theme;
    return window.matchMedia('(prefers-color-scheme: dark)').matches ? 'dark' : 'light';
  }}

  function paint() {{
    var dark = current() === 'dark';
    label.textContent = dark ? 'Light' : 'Dark';
    btn.setAttribute('aria-pressed', String(dark));
    btn.setAttribute('aria-label', dark ? 'Switch to light theme' : 'Switch to dark theme');
  }}

  btn.addEventListener('click', function () {{
    var next = current() === 'dark' ? 'light' : 'dark';
    root.dataset.theme = next;
    try {{ localStorage.setItem('theme', next); }} catch (err) {{ /* ignore */ }}
    paint();
  }});

  window.matchMedia('(prefers-color-scheme: dark)').addEventListener('change', function () {{
    if (!root.dataset.theme) paint();
  }});

  paint();
}})();
</script>
</body>
</html>
"""


def build_sitemap(d: dict) -> str:
    return (
        '<?xml version="1.0" encoding="UTF-8"?>\n'
        '<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">\n'
        f"  <url><loc>{d['site']['url']}</loc></url>\n"
        "</urlset>\n"
    )


def build_robots(d: dict) -> str:
    return "User-agent: *\nAllow: /\n\n" f"Sitemap: {d['site']['url']}sitemap.xml\n"


def main() -> int:
    if not DATA.exists():
        print(f"missing {DATA}", file=sys.stderr)
        return 1

    data = json.loads(DATA.read_text(encoding="utf-8"))

    OUT_HTML.write_text(build_page(data), encoding="utf-8")
    OUT_SITEMAP.write_text(build_sitemap(data), encoding="utf-8")
    OUT_ROBOTS.write_text(build_robots(data), encoding="utf-8")

    state = "on" if data.get("labs", {}).get("enabled") else "off"
    print(f"index.html   {OUT_HTML.stat().st_size:>6} bytes")
    print(f"sitemap.xml  {OUT_SITEMAP.stat().st_size:>6} bytes")
    print(f"robots.txt   {OUT_ROBOTS.stat().st_size:>6} bytes")
    print(f"labs section {state}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
