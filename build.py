def icon(name: str) -> str:
    body = ICONS.get(name)
    if not body:
        return ""
    return (
        '<svg viewBox="0 0 24 24" width="20" height="20" fill="currentColor" '
        f'aria-hidden="true" focusable="false">{body}</svg>'
    )


# --------------------------------------------------------------------------
# Section builders
# --------------------------------------------------------------------------


def band(section_id: str, heading: str, note: str, body: str, extra_class: str = "") -> str:
    note_html = f'\n        <p class="rail__note">{e(note)}</p>' if note else ""
    cls = f"band {extra_class}".strip()
    return f"""
    <section class="{cls}" id="{a(section_id)}" aria-labelledby="{a(section_id)}-heading">
      <div class="rail">
        <h2 class="rail__heading" id="{a(section_id)}-heading">{e(heading)}</h2>{note_html}
      </div>
      <div class="band__body">
{body}
      </div>
    </section>"""


def build_hero(d: dict) -> str:
    site = d["site"]
    hero = d["hero"]
    items = list(hero["links"])
    labs = d.get("labs", {})
    if labs.get("enabled") and labs.get("channelHref"):
        items.append({"label": "YouTube", "href": labs["channelHref"]})
    links = "\n".join(
        f'          <li><a class="pill" href="{a(l["href"])}" target="_blank" rel="noopener">{e(l["label"])}</a></li>'
        for l in items
    )
    return f"""
    <section class="hero" aria-labelledby="hero-name">
      <h1 class="hero__name" id="hero-name">{e(site["name"])}</h1>
      <p class="hero__role">Solutions Architect <span class="amp">&amp;</span><br>Site Reliability Engineer</p>
      <p class="hero__lead">{e(hero["lead"])}</p>
      <ul class="hero__links">
{links}
      </ul>
    </section>"""


def build_about(d: dict) -> str:
    about = d["about"]
    body = "\n".join(f'        <p class="prose">{e(p)}</p>' for p in about["paragraphs"])
    return band("approach", about["heading"], "", body)


def build_timeline(d: dict) -> str:
    tl = d["timeline"]
    rows = []
    for item in tl["entries"]:
        end = item.get("end", "")
        span = f'{e(item["start"])}<span class="dash">–</span>{e(end)}'
        current = " is-current" if item.get("current") else ""
        rows.append(
            f"""        <li class="stint{current}">
          <p class="stint__span">{span}</p>
          <div class="stint__detail">
            <h3 class="stint__role">{e(item["role"])}</h3>
            <p class="stint__org">{e(item["org"])}</p>
            <p class="stint__summary">{e(item["summary"])}</p>
          </div>
        </li>"""
        )
    body = '        <ol class="stints">\n' + "\n".join(rows) + "\n        </ol>"
    return band("track-record", tl["heading"], tl.get("note", ""), body)


def build_certifications(d: dict) -> str:
    certs = d["certifications"]
    rows = []
    for c in certs["items"]:
        abbr = f' <span class="cert__abbr">{e(c["abbr"])}</span>' if c.get("abbr") else ""
        rows.append(
            f"""          <li class="cert">
            <span class="cert__name">{e(c["name"])}{abbr}</span>
            <span class="cert__issuer">{e(c["issuer"])}</span>
          </li>"""
        )
    body = '        <ul class="certs">\n' + "\n".join(rows) + "\n        </ul>"
    return band("certifications", certs["heading"], "", body)


def build_projects(d: dict) -> str:
    p = d["projects"]
    cards = []
    for item in p["items"]:
        tags = ""
        if item.get("tags"):
            tags = (
                '\n            <p class="card__tags">'
                + " ".join(f'<span class="tag">{e(t)}</span>' for t in item["tags"])
                + "</p>"
            )
        cards.append(
            f"""          <li class="card">
            <h3 class="card__title"><a href="{a(item["href"])}" target="_blank" rel="noopener">{e(item["name"])}</a></h3>
            <p class="card__summary">{e(item["summary"])}</p>{tags}
          </li>"""
        )
    body = (
        '        <ul class="cards">\n'
        + "\n".join(cards)
        + "\n        </ul>\n"
        + f'        <p class="band__more"><a href="{a(p["allHref"])}" target="_blank" rel="noopener">{e(p["allLabel"])}</a></p>'
    )
    return band("projects", p["heading"], p.get("note", ""), body)


def build_writing(d: dict) -> str:
    w = d["writing"]
    rows = []
    for item in w["items"]:
        rows.append(
            f"""          <li class="piece">
            <a class="piece__link" href="{a(item["href"])}" target="_blank" rel="noopener">
              <span class="piece__title">{e(item["title"])}</span>
              <time class="piece__date" datetime="{a(item["date"])}">{e(item["dateLabel"])}</time>
            </a>
          </li>"""
        )
    body = (
        '        <ul class="pieces">\n'
        + "\n".join(rows)
        + "\n        </ul>\n"
        + f'        <p class="band__more"><a href="{a(w["allHref"])}" target="_blank" rel="noopener">{e(w["allLabel"])}</a></p>'
    )
    return band("writing", w["heading"], w.get("note", ""), body)


def build_labs(d: dict) -> str:
    """Return the labs section, or an empty string when the flag is off."""
    labs = d.get("labs", {})
    if not labs.get("enabled"):
        return ""
    rows = []
    for item in labs["items"]:
        if item.get("href"):
            title = (
                f'<h3 class="lab__title"><a href="{a(item["href"])}" target="_blank" rel="noopener">'
                f'{e(item["title"])}</a></h3>'
            )
            repo = f'<p class="lab__repo">{e(item["repo"])}</p>' if item.get("repo") else ""
        else:
            title = f'<h3 class="lab__title">{e(item["title"])}</h3>'
            repo = ""
        rows.append(
            f"""          <li class="lab">
            {title}
            <p class="lab__summary">{e(item["summary"])}</p>
            {repo}
          </li>"""
        )
    body = (
        '        <ul class="labs">\n'
        + "\n".join(rows)
        + "\n        </ul>\n"
        + f'        <p class="band__more"><a href="{a(labs["channelHref"])}" target="_blank" rel="noopener">'
        + f'{e(labs["allLabel"])} <span class="handle">{e(labs["channelHandle"])}</span></a></p>'
    )
    return band("labs", labs["heading"], labs.get("note", ""), body)


def build_footer(d: dict) -> str:
    site = d["site"]
    items = list(d["footer"]["links"])
    labs = d.get("labs", {})
    if labs.get("enabled") and labs.get("channelHref"):
        items.append({"label": labs.get("channelName", "YouTube"),
                      "href": labs["channelHref"], "icon": "youtube"})
    links = "\n".join(
        f'        <li><a href="{a(l["href"])}" target="_blank" rel="noopener" aria-label="{a(l["label"])}">'
        f'{icon(l["icon"])}</a></li>'
        for l in items
    )
    return f"""
  <footer class="footer">
    <ul class="footer__links">
{links}
    </ul>
    <p class="footer__legal">&copy; {site["year"]} {e(site["name"])}</p>
  </footer>"""


def build_jsonld(d: dict) -> str:
    site = d["site"]
    same_as = [l["href"] for l in d["hero"]["links"]]
    labs = d.get("labs", {})
    if labs.get("enabled") and labs.get("channelHref"):
        same_as.append(labs["channelHref"])
    payload = {
        "@context": "https://schema.org",
        "@type": "Person",
        "name": site["name"],
        "alternateName": site["shortName"],
        "url": site["url"],
        "jobTitle": site["role"],
        "address": {
            "@type": "PostalAddress",
            "addressLocality": site["locality"],
            "addressCountry": site["country"],
        },
        "knowsAbout": [
            "Site Reliability Engineering",
            "Solution Architecture",
            "Technical Consulting",
            "Kubernetes",
            "Terraform",
            "Observability",
            "Cloud Cost Optimization",
        ],
        "knowsLanguage": ["Spanish", "English"],
        "hasCredential": [
            {
                "@type": "EducationalOccupationalCredential",
                "name": c["name"],
                "credentialCategory": "certification",
                "recognizedBy": {"@type": "Organization", "name": c["issuer"]},
            }
            for c in d["certifications"]["items"]
        ],
        "sameAs": same_as,
    }
    return json.dumps(payload, indent=2, ensure_ascii=False)


