#!/usr/bin/env python3
"""Generate index.html, sitemap.xml and robots.txt from data/site.json.

No third-party dependencies. Run from the repository root:

    python3 build.py

Everything the site says lives in data/site.json. This file decides how it
looks. The labs section is written only when data/site.json sets
labs.enabled to true; while it is false nothing about the channel reaches
the generated HTML.
"""

